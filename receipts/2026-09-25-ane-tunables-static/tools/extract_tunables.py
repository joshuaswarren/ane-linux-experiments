def table_bytes(entries):
    out = b""
    for off, clr, setv in entries:
        out += struct.pack("<III", off, clr, setv)
    out += struct.pack("<III", 0xffffffff, 0, 0)  # terminator
    return out

def load_macho_segments(data):
    ncmds, = struct.unpack_from("<I", data, 16)
    off = 32
    segs = []
    while off < 32 + ncmds * 8 and off < len(data):
        cmd, csize = struct.unpack_from("<II", data, off)
        if cmd == 0x19:  # LC_SEGMENT_64
            name = data[off+8:off+24].rstrip(b"\0").decode()
            vm, msz, fo, fsz = struct.unpack_from("<QQQQ", data, off+24)
            segs.append((name, vm, msz, fo, fsz))
        off += csize
    return segs

def off2va(segs, fo):
    for name, vm, msz, f, fsz in segs:
        if f <= fo < f + fsz:
            return vm + (fo - f), name
    return None, None

def main(path):
    data = open(path, "rb").read()
    segs = load_macho_segments(data)
    print(f"# {path}: {len(data)} bytes, segments:")
    for name, vm, msz, fo, fsz in segs:
        print(f"#   {name:16s} va={vm:#x} size={msz:#x} file={fo:#x}")
    found = 0
    for name, entries, base in T8103_SEQS:
        pat = table_bytes(entries)
        hits = []
        start = 0
        while True:
            i = data.find(pat, start)
            if i < 0:
                break
            hits.append(i)
            start = i + 1
        for fo in hits:
            va, seg = off2va(segs, fo)
            print(f"HIT {name:12s} entries={len(entries):3d} base={base:#x} "
                  f"file={fo:#x} va={va:#x} seg={seg}")
            found += 1
        if not hits:
            print(f"MISS {name:12s} entries={len(entries):3d} base={base:#x}")
    print(f"# {found}/{len(T8103_SEQS)} sequences reproduced")

if __name__ == "__main__":
    main(sys.argv[1])
